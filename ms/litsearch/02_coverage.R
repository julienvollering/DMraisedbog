# Claim coverage from the existing library ####
#
# Literature search, step 2 checkpoint (ms/LITSEARCH_PLAN.md §5). Outside R/RUNALL.R.
# Run from the repository root: Rscript --vanilla ms/litsearch/02_coverage.R
#
# Reads  ms/litsearch/claims.csv, library.csv (01_resolve_bib.R), library_tags.csv
#        (hand-tagged: one row per entry x claim, relevance 1-3)
# Writes ms/litsearch/coverage.md

library(dplyr)
library(readr)
library(stringr)
library(purrr)

LS <- "ms/litsearch"
claims <- read_csv(file.path(LS, "claims.csv"), show_col_types = FALSE)
lib <- read_csv(file.path(LS, "library.csv"), show_col_types = FALSE)
tags <- read_csv(file.path(LS, "library_tags.csv"), show_col_types = FALSE)

stopifnot(
  "tag for a key not in the .bib" = all(tags$key %in% lib$key),
  "tag for an unknown claim" = all(tags$claim_id %in% claims$claim_id),
  "duplicate key x claim tag" = !anyDuplicated(tags[c("key", "claim_id")])
)

tagged <- tags |>
  left_join(
    lib |> select(key, year, cited_in_ms, n_highlights, is_oa, match),
    by = "key"
  )

summ <- claims |>
  left_join(
    tagged |>
      group_by(claim_id) |>
      summarise(
        n_strong = sum(relevance >= 2),
        n_core = sum(relevance == 3),
        n_cited = sum(cited_in_ms & relevance >= 2),
        n_contrast = sum(role == "contrast" & relevance >= 2),
        n_no_hl = sum(relevance >= 2 & coalesce(n_highlights, 0L) == 0),
        .groups = "drop"
      ),
    by = "claim_id"
  ) |>
  mutate(across(starts_with("n_"), \(x) coalesce(x, 0L))) |>
  mutate(
    status = case_when(
      n_core >= 3 ~ "covered",
      n_strong >= 2 ~ "partial",
      n_strong == 1 ~ "thin",
      TRUE ~ "gap"
    )
  )

ref_line <- function(d) {
  d |>
    arrange(desc(relevance), desc(cited_in_ms), key) |>
    mutate(
      flags = paste0(
        ifelse(cited_in_ms, " · cited", ""),
        ifelse(coalesce(n_highlights, 0L) == 0, " · no highlights", paste0(" · ", n_highlights, " hl")),
        ifelse(role == "contrast", " · **contrast**", "")
      ),
      txt = sprintf("  - `%s` (%s)%s: %s", key, relevance, flags, note)
    ) |>
    pull(txt)
}

lines <- c(
  "# Claim coverage from the existing library",
  "",
  sprintf("Generated by `ms/litsearch/02_coverage.R` on %s.", Sys.Date()),
  "",
  sprintf(
    "Library: %d `.bib` entries; %d resolved in OpenAlex (%d by DOI, %d by title); %d cited in `ms.qmd`; %d with JV highlights. %d entries tagged to at least one claim.",
    nrow(lib), sum(lib$match != "unresolved"), sum(lib$match == "doi"), sum(lib$match == "title"),
    sum(lib$cited_in_ms), sum(lib$n_highlights > 0, na.rm = TRUE), n_distinct(tags$key)
  ),
  "",
  "Relevance: 3 core, 2 useful, 1 marginal. Status: *covered* = 3+ core references;",
  "*partial* = 2+ at relevance >= 2; *thin* = 1; *gap* = none.",
  "",
  "## Summary",
  "",
  "| Claim | Block | Priority | Status | Rel. >= 2 | Core | Cited now | Contrast | Without highlights |",
  "|---|---|---|---|---:|---:|---:|---:|---:|",
  sprintf(
    "| %s | %s | %s | %s | %d | %d | %d | %d | %d |",
    summ$claim_id, summ$block, summ$priority, summ$status,
    summ$n_strong, summ$n_core, summ$n_cited, summ$n_contrast, summ$n_no_hl
  ),
  "",
  "## By claim",
  ""
)
for (i in seq_len(nrow(summ))) {
  cid <- summ$claim_id[i]
  d <- tagged |> filter(claim_id == cid)
  lines <- c(
    lines,
    sprintf("### %s (%s) — %s", cid, summ$status[i], claims$claim[claims$claim_id == cid]),
    "",
    if (nrow(d)) ref_line(d) else "  - *nothing in the library*",
    ""
  )
}
untagged <- lib |> filter(!key %in% tags$key)
lines <- c(
  lines,
  "## Library entries not tagged to any claim",
  "",
  sprintf("%d entries (methods tried and retired, general ML, unrelated tools):", nrow(untagged)),
  paste0("`", untagged$key, "`", collapse = ", "),
  ""
)
write_lines(lines, file.path(LS, "coverage.md"))
summ |> select(claim_id, priority, status, n_strong, n_core, n_cited) |> print(n = Inf)

